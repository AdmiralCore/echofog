// Writes the voucher fixture shared by the contract tests and the Go tests. Run it only when the
// voucher format or the contract code changes on purpose: `npx ts-node scripts/makeFixture.ts`.
// Both test suites then check that they produce exactly these bytes.
import { Address } from '@ton/core';
import { keyPairFromSeed } from '@ton/crypto';
import * as fs from 'fs';
import * as path from 'path';
import { MAINNET_GLOBAL_ID, signVoucher, vaultFor } from '../wrappers/EchoFogVault';

async function main() {
    const seed = Buffer.alloc(32);
    for (let i = 0; i < 32; i++) seed[i] = i + 1;
    const keys = keyPairFromSeed(seed);
    const owner = Address.parseRaw('0:' + '11'.repeat(32));
    const node = Address.parseRaw('0:' + '22'.repeat(32));
    const vault = await vaultFor(owner, keys.publicKey);
    const cumulative = 3906n * 1024n; // 1 GB at 3906 nanoton per MB
    const { cell, signature } = signVoucher({ globalId: MAINNET_GLOBAL_ID, vault: vault.address, node, cumulative }, keys.secretKey);
    const fx = {
        note: 'generated by contracts/vault/scripts/makeFixture.ts; checked by the contract tests and by voucher_test.go',
        seed_hex: seed.toString('hex'),
        pubkey_hex: keys.publicKey.toString('hex'),
        owner: owner.toRawString(),
        node: node.toRawString(),
        global_id: MAINNET_GLOBAL_ID,
        cumulative: cumulative.toString(),
        code_hash_hex: vault.init!.code.hash().toString('hex'),
        data_hash_hex: vault.init!.data.hash().toString('hex'),
        vault_raw: vault.address.toRawString(),
        voucher_boc_hex: cell.toBoc().toString('hex'),
        voucher_hash_hex: cell.hash().toString('hex'),
        signature_hex: signature.toString('hex'),
    };
    const out = path.join(__dirname, '../../../internal/wallet/tonwallet/testdata/voucher_fixture.json');
    fs.writeFileSync(out, JSON.stringify(fx, null, 2) + '\n');
    console.log('wrote', out);
}

main();
